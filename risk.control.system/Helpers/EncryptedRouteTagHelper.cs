using Microsoft.AspNetCore.Razor.TagHelpers;
using risk.control.system.Services.Common;

namespace risk.control.system.Helpers
{
    [HtmlTargetElement("a", Attributes = "asp-route-id")]
    [HtmlTargetElement("form", Attributes = "asp-route-id")]
    public class EncryptedRouteTagHelper(IEncryptionService encryptionService) : TagHelper
    {
        private readonly IEncryptionService _encryptionService = encryptionService;

        [HtmlAttributeName("asp-route-id")]
        public object RouteId { get; set; } = null!;

        public override void Process(TagHelperContext context, TagHelperOutput output)
        {
            var routeIdStr = RouteId?.ToString();
            if (!string.IsNullOrEmpty(routeIdStr))
            {
                string encryptedId = long.TryParse(routeIdStr, out long numericId)
                    ? _encryptionService.ProtectId(numericId)
                    : routeIdStr;

                output.Attributes.SetAttribute("asp-route-id", encryptedId);

                if (output.TagName.Equals("form", StringComparison.OrdinalIgnoreCase))
                {
                    // Forcefully construct the action URL with the encrypted token
                    var actionAttr = output.Attributes["action"]?.Value?.ToString();
                    if (!string.IsNullOrEmpty(actionAttr))
                    {
                        // Remove trailing raw numeric ID if generated by MVC
                        var cleanedAction = System.Text.RegularExpressions.Regex.Replace(actionAttr, @"/\d+$", "");
                        output.Attributes.SetAttribute("action", $"{cleanedAction}/{encryptedId}");
                    }

                    output.PostContent.AppendHtml($"<input type=\"hidden\" name=\"id\" value=\"{encryptedId}\" />");
                }
            }
            base.Process(context, output);
        }
    }
}